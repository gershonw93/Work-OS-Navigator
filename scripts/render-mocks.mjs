// Photographs the website's app mocks into public/marketing/mocks and writes
// their sizes to components/marketing/mock-images.ts.
//
//   npx next dev -p 3456 &
//   node scripts/render-mocks.mjs http://localhost:3456
//
// Why pictures: see components/marketing/mock-image.tsx.
import { createRequire } from 'node:module'
import sharp from 'sharp'
import { writeFileSync, mkdirSync } from 'node:fs'

// Playwright is not a dependency of the app; use the copy the machine has
// (a project install, or a global one on NODE_PATH).
const { chromium } = createRequire(import.meta.url)('playwright')

const base = process.argv[2] ?? 'http://localhost:3456'
const OUT = 'public/marketing/mocks'
const SCALE = 2

// name -> the box each render is taken in. A fixed height crops (the hero's
// monitor shows the top of a long screen); no height means "as tall as it is".
const MOCKS = {
  projects: { breakpoint: 768, desktop: { w: 1480, h: 940 }, mobile: { w: 356, h: 380 } },
  'quote-scan': { breakpoint: 640, desktop: { w: 560 }, mobile: { w: 358 } },
  money: { breakpoint: 640, desktop: { w: 560 }, mobile: { w: 358 } },
  schedule: { breakpoint: 640, desktop: { w: 560 }, mobile: { w: 358 } },
  compare: { breakpoint: 640, desktop: { w: 560 }, mobile: { w: 358 } },
  dashboard: { breakpoint: 640, desktop: { w: 600 }, mobile: { w: 358 } },
}

mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch()
const sizes = {}
for (const [name, spec] of Object.entries(MOCKS)) {
  sizes[name] = { breakpoint: spec.breakpoint }
  for (const viewport of ['desktop', 'mobile']) {
    const box = spec[viewport]
    for (const theme of ['light', 'dark']) {
      // The page is as wide as the layout the render is meant to show: the
      // mocks are responsive, so a 358px box in a 1440px window would draw
      // the desktop layout squeezed rather than the phone one.
      const width = viewport === 'mobile' ? 420 : Math.max(1440, box.w + 100)
      const page = await browser.newPage({ viewport: { width, height: 1200 }, deviceScaleFactor: SCALE, colorScheme: theme })
      const q = new URLSearchParams({ w: String(box.w), theme, ...(box.h ? { h: String(box.h) } : {}) })
      await page.goto(`${base}/dev-render/${name}?${q}`, { waitUntil: 'networkidle' })
      await page.evaluate(() => document.fonts.ready)
      const el = page.locator('#mock')
      const png = await el.screenshot()
      const r = await el.boundingBox()
      await sharp(png).webp({ quality: 88 }).toFile(`${OUT}/${name}-${viewport}-${theme}.webp`)
      sizes[name][viewport] = { w: Math.round(r.width), h: Math.round(r.height) }
      await page.close()
      console.log(`${name} ${viewport} ${theme}: ${Math.round(r.width)}x${Math.round(r.height)}`)
    }
  }
}
await browser.close()

writeFileSync('components/marketing/mock-images.ts', `// GENERATED by scripts/render-mocks.mjs - do not edit by hand.
// CSS-pixel sizes of each rendered mock (the files are ${SCALE}x).

export const MOCK_IMAGES = ${JSON.stringify(sizes, null, 2)} as const

export type MockName = keyof typeof MOCK_IMAGES
`)
